part of '../levit_monitor.dart';

/// Function signature for sensitive data obfuscation.
typedef LevitObfuscator = String Function(dynamic value);

/// The authoritative entry point for application monitoring and diagnostics.
///
/// [LevitMonitor] acts as a unified hub that collects events from both the
/// dependency injection system and the reactive state engine. It processes
/// these events through a filtering pipeline and dispatches them to a
/// [LevitTransport] for inspection or storage.
class LevitMonitor {
  static LevitMonitorMiddleware? _middleware;

  /// The active predicate used to filter outgoing events.
  static bool Function(MonitorEvent event)? _filter;

  /// The active obfuscator used for sensitive data.
  static LevitObfuscator _obfuscator = (value) => '***';

  /// The minimum log level to emit. Logs below this level will be dropped.
  static Level _logLevel = Level.all;

  /// Returns the current minimum log level.
  static Level get logLevel => _logLevel;

  /// Returns the current event filter, if any.
  static bool Function(MonitorEvent event)? get filter => _filter;

  /// Configures a global filter to selectively process monitor events.
  ///
  /// The [filter] function receives every [MonitorEvent] generated by the
  /// system. Returning `true` allows the event to proceed to the transport.
  ///
  /// ### Examples
  /// ```dart
  /// // Exclude specific reactive variables by name
  /// LevitMonitor.setFilter((e) => e is! ReactiveEvent || e.reactive.name != 'secret');
  ///
  /// // Only monitor Dependency Injection events
  /// LevitMonitor.setFilter((e) => e is DependencyEvent);
  /// ```
  static void setFilter(bool Function(MonitorEvent event)? filter) {
    _filter = filter;
  }

  /// Configures a global obfuscator for sensitive data.
  static void setObfuscator(LevitObfuscator? obfuscator) {
    _obfuscator = obfuscator ?? (value) => '***';
  }

  /// Sets the minimum log level for [LevitMonitor].
  static void setLogLevel(Level level) {
    _logLevel = level;
  }

  /// Obfuscates a [value] if it is considered sensitive.
  static dynamic obfuscate(dynamic value) {
    try {
      return _obfuscator(value);
    } catch (_) {
      return '***';
    }
  }

  /// Evaluates whether a specific [event] should be processed based on the
  /// current filter configuration.
  static bool shouldProcess(MonitorEvent event) {
    return _filter == null || _filter!(event);
  }

  /// Emits a diagnostic log event to the monitoring pipeline.
  ///
  /// The [data] parameter can be a simple message string or a structured,
  /// JSON-serializable object. Set [sensitive] to `true` to redact payload and
  /// error details before buffering and export.
  static void log(
    Object? data, {
    Level level = Level.info,
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) {
    if (_middleware == null) return;
    if (level.value < _logLevel.value) return;

    final event = LogEvent(
      sessionId: _middleware!.sessionId,
      level: level,
      data: data,
      sensitive: sensitive,
      error: error,
      stackTrace: stackTrace,
    );
    _middleware!._addToBuffer(event);
  }

  /// Emits a dependency-neutral structured custom event.
  ///
  /// Optional packages should translate their own event types at the
  /// application boundary and call this method instead of adding dependencies
  /// to `levit_monitor`.
  static void emitCustomEvent({
    required String namespace,
    required String name,
    Map<String, Object?> attributes = const {},
    Level level = Level.info,
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) {
    final middleware = _middleware;
    if (middleware == null) return;
    middleware._addToBuffer(
      CustomMonitorEvent(
        sessionId: middleware.sessionId,
        namespace: namespace,
        name: name,
        attributes: attributes,
        level: level,
        sensitive: sensitive,
        error: error,
        stackTrace: stackTrace,
      ),
    );
  }

  /// Helper method for emitting a log at [Level.trace].
  static void logTrace(
    Object? data, {
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) => log(
    data,
    level: Level.trace,
    sensitive: sensitive,
    error: error,
    stackTrace: stackTrace,
  );

  /// Helper method for emitting a log at [Level.debug].
  static void logDebug(
    Object? data, {
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) => log(
    data,
    level: Level.debug,
    sensitive: sensitive,
    error: error,
    stackTrace: stackTrace,
  );

  /// Helper method for emitting a log at [Level.info].
  static void logInfo(
    Object? data, {
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) => log(
    data,
    level: Level.info,
    sensitive: sensitive,
    error: error,
    stackTrace: stackTrace,
  );

  /// Helper method for emitting a log at [Level.warning].
  static void logWarning(
    Object? data, {
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) => log(
    data,
    level: Level.warning,
    sensitive: sensitive,
    error: error,
    stackTrace: stackTrace,
  );

  /// Helper method for emitting a log at [Level.error].
  static void logError(
    Object? data, {
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) => log(
    data,
    level: Level.error,
    sensitive: sensitive,
    error: error,
    stackTrace: stackTrace,
  );

  /// Helper method for emitting a log at [Level.fatal].
  static void logFatal(
    Object? data, {
    bool sensitive = false,
    Object? error,
    StackTrace? stackTrace,
  }) => log(
    data,
    level: Level.fatal,
    sensitive: sensitive,
    error: error,
    stackTrace: stackTrace,
  );

  /// Bootstraps the monitoring system and attaches it to the application.
  ///
  /// By default, [LevitMonitor] uses a [ConsoleTransport] which pipes JSON-encoded
  /// events to standard output.
  ///
  /// *   [transport]: A single destination for monitor events.
  /// *   [transports]: A list of destinations for monitor events. If provided,
  ///     it will be combined with [transport] if both are present.
  static Future<void> _lifecycle = Future.value();
  static bool? _previousWorkerMonitoring;
  static Future<void> _serialize(Future<void> Function() action) {
    final operation = _lifecycle.then((_) => action());
    _lifecycle = operation.then<void>(
      (_) {},
      onError: (Object _, StackTrace __) {},
    );
    return operation;
  }

  /// Enables bounded event history and worker statistics only when requested.
  static Future<void> attach({
    LevitTransport? transport,
    List<LevitTransport>? transports,
    int historyCapacity = 0,
    int maxPendingEvents = 1024,
    bool includeStackTrace = false,
    bool enableWorkerStatistics = false,
  }) => _serialize(() async {
    await _detachNow();
    final all = [if (transport != null) transport, ...?transports];
    final sink = all.isEmpty
        ? ConsoleTransport()
        : all.length == 1
        ? all.single
        : MultiTransport(all);
    final middleware = LevitMonitorMiddleware(
      transport: sink,
      includeStackTrace: includeStackTrace,
      historyCapacity: historyCapacity,
      maxPendingEvents: maxPendingEvents,
    );
    _previousWorkerMonitoring = Lx.enableWatchMonitoring;
    if (enableWorkerStatistics) Lx.enableWatchMonitoring = true;
    _middleware = middleware;
    middleware.enable();
  });

  static Future<void> _detachNow() async {
    final previous = _middleware;
    _middleware = null;
    if (previous == null) return;
    try {
      await previous.close();
    } finally {
      if (_previousWorkerMonitoring != null) {
        Lx.enableWatchMonitoring = _previousWorkerMonitoring!;
      }
      _previousWorkerMonitoring = null;
    }
  }

  /// Completes only after admitted events and transport cleanup finish.
  static Future<void> detach() => _serialize(_detachNow);

  /// Waits for attachment/replacement and all admitted event delivery.
  static Future<void> flush() => _serialize(() async {
    await _middleware?.flush();
  });
  static int get droppedEvents => _middleware?.droppedEvents ?? 0;
  static List<LevitEventEnvelope> get history =>
      _middleware?.history ?? const [];
  static Map<String, dynamic>? get snapshot => _middleware?.snapshot;
}

/// Failures from awaited event delivery/cleanup, after all cleanup was attempted.
final class LevitMonitorException implements Exception {
  final List<AsyncError> failures;
  LevitMonitorException(Iterable<AsyncError> failures)
    : failures = List.unmodifiable(failures);
  @override
  String toString() =>
      'LevitMonitorException(${failures.length} recorded failures)';
}
